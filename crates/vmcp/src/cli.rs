//! Operator CLI: `init`, `add|list|get|remove` for mcp / tool / skill / tasks.
//!
//! Surface (same idea as `npm add` / Claude `mcp add`):
//! ```text
//! vmcp init
//! vmcp add mcp --transport http notion https://mcp.notion.com/mcp
//! vmcp add tool presentation build_presentation --task-support optional
//! vmcp add skill search_docs --description "…" --template "…"
//! vmcp add tasks
//! vmcp list mcp|tool|skill
//! ```
//!
//! `vmcp mcp …` remains as a thin alias for the mcp target.

