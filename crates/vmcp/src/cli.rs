//! Operator CLI helpers: `vmcp init` and `vmcp mcp …` (Claude-style).
//!
//! Registry mutations load/save via [`vmcp_registry::load_registry_raw`] so
//! `${ENV}` placeholders are not expanded on round-trip.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use clap::{Subcommand, ValueEnum};
use vmcp_registry::{
    add_upstream, get_upstream, load_registry_raw, remove_upstream, save_registry_atomic,
    UpstreamSpec, UpstreamTransport,
};

